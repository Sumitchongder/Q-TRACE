"""Physics score test (Rao / Neyman C(alpha)) on the honest manifold.

The omnibus residual channel of :mod:`qtrace.detect.detector` is
consistent against every deviation but spreads its power over 96
directions. Physically realisable deviations, however, move the outcome
table along a small number of directions: those generated by perturbing
the device parameters. The score test projects the data onto exactly
these directions.

Parameters probed (all evaluated at the calibrated honest point):

====================  ======================================================
``e_Z``, ``e_X``      optical error per basis (logit scale)
``p_d0``, ``p_d1``    per-detector background (log scale)
``kappa``             relative detector efficiency (log scale)
``rho``               decoy/signal intensity ratio, i.e. the decoy relation
``delta_e_decoy``     intensity-dependent error (zero for honest links)
``double``            double-click excess (zero for honest links)
``eps_X``             basis-dependent receiver efficiency (zero for honest)
``eta``               transmittance (nuisance), removed by Schur complement
====================  ======================================================

plus the five free setting probabilities ``(p_a1, p_alphaZ, p_betaZ,
p_decoy, p_vacuum)``. With per-window score ``u_t`` and Fisher
information ``I_t`` (efficient for the nuisance), the accumulated
statistic over a horizon ``M`` is::

    S_M = (sum u_t)^T (sum I_t)^{-1} (sum u_t)   ~  chi2_q   under H0,

which is locally most powerful against small deviations in the span of
the probed directions. No attack data enter its construction.
"""

from __future__ import annotations

import numpy as np
from scipy.special import expit, logit

from qtrace.detect.honest_model import HonestParams, model_probs
from qtrace.physics.optics import setting_probabilities

PHYS_NAMES = ("e_Z", "e_X", "p_d0", "p_d1", "kappa", "rho", "delta_e_decoy", "double", "eps_X")
SETTING_NAMES = ("p_a1", "p_alphaZ", "p_betaZ", "p_decoy", "p_vacuum")


def extended_probs(params: HonestParams, eta, theta):
    """Outcome probabilities with the relaxation parameters ``theta`` (len 10).

    ``theta`` is a displacement from the calibrated point in the
    transformed coordinates listed in :data:`PHYS_NAMES`, followed by
    ``log eta``.
    """
    p = HonestParams(
        e_z=float(expit(logit(params.e_z) + theta[0])),
        e_x=float(expit(logit(params.e_x) + theta[1])),
        pd0=params.pd0 * np.exp(theta[2]), pd1=params.pd1 * np.exp(theta[3]),
        kappa=params.kappa * np.exp(theta[4]), rho=params.rho * np.exp(theta[5]),
        mu_s=params.mu_s, afterpulse=params.afterpulse, p_k=params.p_k)
    eta = np.asarray(eta) * np.exp(theta[9])
    base = model_probs(p, eta)
    if theta[6] != 0.0:
        pd = HonestParams(**{**p.__dict__,
                             "e_z": float(expit(logit(p.e_z) + theta[6])),
                             "e_x": float(expit(logit(p.e_x) + theta[6]))})
        base[:, 1] = model_probs(pd, eta)[:, 1]
    if theta[8] != 0.0:
        bx = model_probs(p, eta * np.exp(theta[8]))
        base[..., 1, :] = bx[..., 1, :]
    if theta[7] != 0.0:
        dbl = base[..., 3] * np.exp(theta[7])
        base[..., 0] = base[..., 0] - (dbl - base[..., 3])
        base[..., 3] = dbl
    return np.clip(base, 1e-300, 1.0)


def _setting_probs_ext(p_k, s):
    pk = np.asarray(p_k, float).copy()
    pk = np.array([pk[0], pk[1] * np.exp(s[3]), pk[2] * np.exp(s[4])])
    pk = pk / pk.sum()
    return setting_probabilities(pk, expit(s[0]), expit(s[1]), expit(s[2]))


class ScoreTest:
    def __init__(self, h=1e-4):
        self.h = h

    def window_scores(self, counts, params: HonestParams, eta):
        """Efficient scores and informations per window.

        Returns ``(u_phys (W,9), I_phys (W,9,9), u_set (W,5), I_set (W,5,5))``.
        """
        counts = np.asarray(counts, float)
        n_set = counts.sum(axis=-1)
        h = self.h
        p0 = extended_probs(params, eta, np.zeros(10))
        grads = []
        for j in range(10):
            th = np.zeros(10)
            th[j] = h
            lp = np.log(extended_probs(params, eta, th))
            th[j] = -h
            lm = np.log(extended_probs(params, eta, th))
            grads.append((lp - lm) / (2 * h))
        w = counts.shape[0]
        g = np.stack(grads, axis=-1).reshape(w, -1, 10)                # (W, cells, 10)
        e = (n_set[..., None] * p0).reshape(w, -1)
        resid = counts.reshape(w, -1) - e
        u = np.einsum("wc,wcj->wj", resid, g)
        info = np.einsum("wc,wcj,wck->wjk", e, g, g)
        # efficient score / information for the nuisance eta (last coordinate)
        i_pn = info[:, :9, 9]
        i_nn = info[:, 9, 9]
        u_eff = u[:, :9] - i_pn * (u[:, 9] / i_nn)[:, None]
        i_eff = info[:, :9, :9] - np.einsum("wj,wk->wjk", i_pn, i_pn) / i_nn[:, None, None]

        # setting allocation: multinomial over 24 settings
        total = n_set.sum(axis=(-4, -3, -2, -1))
        s0 = np.zeros(5)
        ps0 = _setting_probs_ext(params.p_k, s0).reshape(-1)
        gs = []
        for j in range(5):
            s = s0.copy()
            s[j] = h
            lp = np.log(_setting_probs_ext(params.p_k, s).reshape(-1))
            s[j] = -h
            lm = np.log(_setting_probs_ext(params.p_k, s).reshape(-1))
            gs.append((lp - lm) / (2 * h))
        gs = np.stack(gs, axis=-1)                                     # (24, 5)
        nflat = n_set.reshape(len(total), -1)
        es = total[:, None] * ps0[None, :]
        u_set = (nflat - es) @ gs
        i_set = total[:, None, None] * (gs.T * ps0) @ gs
        return u_eff, i_eff, u_set, i_set


def inv_sqrt_psd(m, floor=1e-12):
    """Batched inverse square root of symmetric positive semi-definite matrices."""
    vals, vecs = np.linalg.eigh(m)
    vals = np.maximum(vals, floor * np.maximum(vals.max(axis=-1, keepdims=True), 1e-300))
    return np.einsum("...ij,...j,...kj->...ik", vecs, vals ** -0.5, vecs)


def dispersion_matrix(u, info, shrinkage=0.3):
    """Excess-noise (dispersion) matrix of the scores from commissioning windows.

    Scores are whitened by their Poisson information, ``w_t = I_t^{-1/2} u_t``;
    under a purely Poissonian honest model ``cov(w) = 1``. Unmodelled
    window-to-window fluctuations (intensity jitter, drift) inflate it. The
    sample covariance is shrunk toward its diagonal and floored at the
    identity so that the honest model is never assumed *less* noisy than
    shot noise.
    """
    w = np.einsum("wij,wj->wi", inv_sqrt_psd(info), u)
    c = np.cov(w, rowvar=False)
    target = np.diag(np.diag(c))
    phi = (1 - shrinkage) * c + shrinkage * target
    vals, vecs = np.linalg.eigh(phi)
    vals = np.maximum(vals, 1.0)
    return (vecs * vals) @ vecs.T


def accumulated_statistic(u, info, horizons, bias=None, n_ref=None, phi=None, ridge=1e-9):
    """Score statistics over trailing horizons, normalised to their chi2 reference.

    ``bias`` is the mean per-window score over ``n_ref`` commissioning
    windows (static model mismatch); subtracting an estimated mean inflates
    the variance of a sum over ``M`` windows by ``1 + M / n_ref``.
    """
    w, q = u.shape
    if bias is not None:
        u = u - bias
    cu = np.vstack([np.zeros((1, q)), np.cumsum(u, axis=0)])
    ci = np.concatenate([np.zeros((1, q, q)), np.cumsum(info, axis=0)])
    idx = np.arange(1, w + 1)
    out = {}
    for m_max in horizons:
        m = np.minimum(idx, m_max)
        U = cu[idx] - cu[idx - m]
        I = ci[idx] - ci[idx - m]
        I = I + ridge * np.trace(I, axis1=1, axis2=2)[:, None, None] * np.eye(q)
        if phi is None:
            s = np.einsum("wj,wj->w", U, np.linalg.solve(I, U[..., None])[..., 0])
        else:
            v = np.einsum("wij,wj->wi", inv_sqrt_psd(I), U)
            s = np.einsum("wj,wj->w", v, np.linalg.solve(phi, v.T).T)
        if bias is not None and n_ref:
            s = s / (1.0 + m / n_ref)
        out[m_max] = (s - q) / np.sqrt(2 * q)
    return out


def local_statistic(u_all, info_all, start, horizons, ref_len, phi=None, ridge=1e-9):
    """Window-limited GLR against a moving reference (drift-robust).

    For each monitoring window ``g >= start`` the recent block ``(g-M, g]``
    is compared with the reference block ``(g-M-R, g-M]`` immediately
    preceding it, ``d = U_recent - (M/R) U_ref``. Static model mismatch and
    drift that is slow on the scale of ``M + R`` windows cancel in ``d``;
    an abrupt change does not. ``u_all``/``info_all`` cover commissioning
    and monitoring windows.
    """
    n, q = u_all.shape
    cu = np.vstack([np.zeros((1, q)), np.cumsum(u_all, axis=0)])
    ci = np.concatenate([np.zeros((1, q, q)), np.cumsum(info_all, axis=0)])
    g = np.arange(start + 1, n + 1)
    out = {}
    for m in horizons:
        lo_rec = np.maximum(g - m, 0)
        mm = g - lo_rec
        lo_ref = np.maximum(lo_rec - ref_len, 0)
        rr = np.maximum(lo_rec - lo_ref, 1)
        U = (cu[g] - cu[lo_rec]) - (mm / rr)[:, None] * (cu[lo_rec] - cu[lo_ref])
        I = ci[g] - ci[lo_rec]
        I = I + ridge * np.trace(I, axis1=1, axis2=2)[:, None, None] * np.eye(q)
        infl = 1.0 + mm / rr
        v = np.einsum("wij,wj->wi", inv_sqrt_psd(I), U)
        sol = v if phi is None else np.linalg.solve(phi, v.T).T
        stat = np.einsum("wj,wj->w", v, sol) / infl
        out[m] = (stat - q) / np.sqrt(2 * q)
    return out
